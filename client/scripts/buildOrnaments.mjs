// Card frame ornaments made from a reference picture instead of drawn by hand:
// brand-src/ornament-<name>.png (dark ornament on a light or checkered
// background) -> public/brand/ornaments/<name>.png, a mask the card colours
// (pixelart.css, `--orn`). The ornament is keyed out by darkness, mirrored if
// needed to a top-left corner, and placed in a square box with its corner
// (where the two rules meet) at 6/64 of the box, the spot .loc-card__orn
// expects. Run by hand: node scripts/buildOrnaments.mjs
import fs from 'fs';
import path from 'path';
import sharp from 'sharp';
import { fileURLToPath } from 'url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(root, 'brand-src');
const OUT = path.join(root, 'public', 'brand', 'ornaments');

const ORNAMENTS = {
  // Epic's corner (2026-11-14, the user's reference picture, a top-right
  // corner): its rules meet at x 106, y 15.5 of the 136 x 108 picture.
  'epic-corner': { src: 'ornament-epic-corner.png', flop: true, corner: [106, 15.5], box: 112, scale: 4 },
  // Mythic's Gothic corner (2026-11-14, the user's reference, a top-left corner
  // of tracery with fleur-de-lis ends): its outer bars meet at x 19, y 4.5.
  'mythic-corner': { src: 'ornament-mythic-corner.png', flop: false, corner: [19, 4.5], box: 132, scale: 4 },
  // Legend's corner (2026-11-14, generated by the user from a prompt: an
  // original acanthus L with a fleur-de-lis, 1024 px, black engraving on
  // white). Its two arms are long, so the card shows it at half its width and
  // the arms of two corners meet in the middle of each edge (pixelart.css).
  // It is drawn in fine lines, so they are thickened (`thicken`, a blur
  // before keying) or they would vanish at that size; `at` 0 puts the corner
  // of the ornament itself (its top-left ink) at the box's corner.
  'legend-corner': { src: 'ornament-legend-corner.png', flop: false, corner: [79, 79], box: 880, scale: 1, at: 0, thicken: 2.2, out: 512 },
};

fs.mkdirSync(OUT, { recursive: true });
for (const [name, { src, flop, corner, box, scale, at = 6 / 64, thicken, out, flips }] of Object.entries(ORNAMENTS)) {
  let img = sharp(path.join(SRC, src)).flatten({ background: '#ffffff' }).greyscale();
  const meta = await sharp(path.join(SRC, src)).metadata();
  if (flop) img = img.flop();
  if (thicken) img = sharp(await img.blur(thicken).png().toBuffer()).greyscale();
  const cx = flop ? meta.width - corner[0] : corner[0];
  const cy = corner[1];
  // Upscale first, so the keyed edge is smooth when the card shows it larger.
  const W = meta.width * scale, H = meta.height * scale;
  const { data } = await img.resize(W, H, { kernel: 'lanczos3' }).extractChannel(0).raw().toBuffer({ resolveWithObject: true });
  // Darkness to alpha: the ornament is dark brown, the checker light grey.
  const B = box * scale;
  const off = at * B;
  const ox = Math.round(cx * scale - off), oy = Math.round(cy * scale - off);
  const rgba = new Uint8Array(B * B * 4);
  for (let y = 0; y < B; y++) {
    for (let x = 0; x < B; x++) {
      const sx = x + ox, sy = y + oy;
      if (sx < 0 || sy < 0 || sx >= W || sy >= H) continue;
      const v = data[sy * W + sx];
      // A thickened line is a blurred one: count its paler fringe too.
      const a = thicken ? Math.max(0, Math.min(1, (232 - v) / 60)) : Math.max(0, Math.min(1, (175 - v) / 90));
      rgba[(y * B + x) * 4 + 3] = Math.round(a * 255);
    }
  }
  const target = path.join(OUT, `${name}.png`);
  let result = sharp(rgba, { raw: { width: B, height: B, channels: 4 } });
  if (out) result = sharp(await result.png().toBuffer()).resize(out, out);
  const buf = await result.png().toBuffer();
  await sharp(buf).png({ compressionLevel: 9 }).toFile(target);
  console.log(`${name}.png`, out || B, `${Math.round(fs.statSync(target).size / 1024)} KB`);
  if (flips) {
    await sharp(buf).flop().png({ compressionLevel: 9 }).toFile(path.join(OUT, `${name}-tr.png`));
    await sharp(buf).flip().png({ compressionLevel: 9 }).toFile(path.join(OUT, `${name}-bl.png`));
    await sharp(buf).flip().flop().png({ compressionLevel: 9 }).toFile(path.join(OUT, `${name}-br.png`));
  }
}

